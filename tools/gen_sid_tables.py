def table(fn):
    t = re.sub(r"/\*.*?\*/", "", (src / fn).read_text(), flags=re.S)
    t = re.sub(r"//.*", "", t)
    v = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", t)]
    assert len(v) == 4096, (fn, len(v))
    assert all(x & 15 == 0 and x < 4096 for x in v), fn
    return [x >> 4 for x in v]


