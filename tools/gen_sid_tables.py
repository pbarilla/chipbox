# pitch: F = Hz 2^24 / clk, a 16 bit number; the accumulator is 24 bits and our phase is those bits << 8
def sid_inc(n):
    hz = 440.0 * 2 ** ((n - 69) / 12)
    F = min(65535.0, hz * 16777216 / SID_CLK)
    return round(F * 256 * SID_CLK / FSO)
arr("SID_INC", "uint32_t", [sid_inc(n) for n in range(128)], 8)
def sid_inc_c(n):                                # the accumulator step each SID cycle (F << 8)
    hz = 440.0 * 2 ** ((n - 69) / 12)
    return round(min(65535.0, hz * 16777216 / SID_CLK) * 256)
arr("SID_INC_C", "uint32_t", [sid_inc_c(n) for n in range(128)], 8)

