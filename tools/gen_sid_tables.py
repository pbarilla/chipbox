def dac(bits, r2r, term):                        # reSID dac.h: R-2R ladder, the 6581's missing its termination
    vbit = []
    for set_bit in range(bits):
        bit = 0
        Vn, R = 1.0, 1.0
        _2R = r2r * R
        Rn = _2R if term else math.inf
        while bit < set_bit:
            Rn = R + _2R if Rn == math.inf else R + _2R * Rn / (_2R + Rn)
            bit += 1
        if Rn == math.inf:
            Rn = _2R
        else:
            Rn = _2R * Rn / (_2R + Rn)
            Vn = Vn * Rn / _2R
        bit += 1
        while bit < bits:
            Rn += R
            I = Vn / Rn
            Rn = _2R * Rn / (_2R + Rn)
            Vn = Rn * I
            bit += 1
        vbit.append(Vn)
    return [int(((1 << bits) - 1) * sum(vbit[j] for j in range(bits) if i >> j & 1) + 0.5) for i in range(1 << bits)]


