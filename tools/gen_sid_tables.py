def arr(name, ctype, vals, per=12):
    flat = list(vals)
    out.append(f"static const {ctype} {name}[{len(flat)}] = {{")
    for i in range(0, len(flat), per):
        out.append("    " + ", ".join(str(v) for v in flat[i:i + per]) + ",")
    out.append("};")


