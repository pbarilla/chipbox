arr("KSL_TMP", "uint8_t", [ksl_tmp(n) for n in N], 16)

# Divider-quantised pitch, so each note lands where the chip's register would put it (and the lowest and highest notes stop where the register does)
def quant(clk_per_div, lo, hi):                  # f = clk_per_div / d, d a whole number lo..hi
    return [inc_k(clk_per_div / max(lo, min(hi, round(clk_per_div / f(n))))) for n in N]
arr("VB_INC", "uint32_t", quant(5000000 / 32, 1, 2048), 8)              # the VSU: 5 MHz / (32 (2048 - x))
arr("WS_INC", "uint32_t", quant(3072000 / 32, 1, 2048), 8)              # WonderSwan: 96000 / (2048 - d)
arr("SCC_INC", "uint32_t", quant(3579545 / 32, 1, 4096), 8)             # the SCC: 3.58 MHz / (32 (N + 1))
arr("VRC6P_INC", "uint32_t", quant(1789773 / 16, 1, 4096), 8)           # VRC6 pulse: 1.79 MHz / (16 (P + 1))
arr("VRC6S_INC", "uint32_t", quant(1789773 / 14, 1, 4096), 8)           # VRC6 saw: 1.79 MHz / (14 (P + 1))
arr("S5B_INC", "uint32_t", quant(1789773 / 32, 1, 4095), 8)             # the 5B: 1.79 MHz / (32 P)
arr("AY_INC", "uint32_t", quant(1773447 / 16, 1, 4095), 8)              # the AY on a Spectrum: 1.773 MHz / (16 P)
arr("SSG_INC", "uint32_t", quant(1996800 / 16, 1, 4095), 8)            # the YM2203 / YM2608 SSG (PC-88, PC-98): clock / 2 or / 4 = 1.9968 MHz / (16 P)
arr("SSGN_INC", "uint32_t", quant(2000000 / 16, 1, 4095), 8)           # the YM2610 SSG (Neo Geo): 8 MHz / 4 = 2 MHz / (16 P)
arr("FDS_INC", "uint32_t", [inc_k(min(4095, round(f(n) / (1789773 / 4194304 * 1.0)))*(1789773 / 4194304)) for n in N], 8)      # the FDS: f = p * clk / 2^22, p 12 bit

# Philips SAA1099 (Sam Coupe): a 3 bit octave and an 8 bit step, f = 15625 * 2^octave / (511 - step), so a note lands on the nearest step
def saa(t):
    best = None
    for o in range(8):
        d = max(256, min(511, round(15625 * 2 ** o / t)))
        fr = 15625 * 2 ** o / d
        if best is None or abs(math.log(fr / t)) < abs(math.log(best / t)): best = fr
    return best
arr("SAA_INC", "uint32_t", [inc_k(saa(f(n))) for n in N], 8)

# MOS 6560 VIC (VIC-20, PAL): three square voices from a 7 bit counter, the clock divided by 256, 128 or 64 first; a note takes the finest voice that reaches it
VIC_CLK = 1108404.5
def vic(t):
    for div in (64, 128, 256):
        k = round(VIC_CLK / div / t)
        if 1 <= k <= 128: return VIC_CLK / div / k
    return VIC_CLK / 256 / 128
arr("VIC_INC", "uint32_t", [inc_k(vic(f(n))) for n in N], 8)

# MOS 7360 TED (Plus/4, PAL): a 10 bit counter, f = clock / 16 / (1024 - n); below the lowest note (about 108 Hz) a note sounds in the octave above
TED_CLK = 1773447
def ted(t):
    while t < TED_CLK / 16 / 1023: t *= 2
    return TED_CLK / 16 / max(1, round(TED_CLK / 16 / t))
arr("TED_INC", "uint32_t", [inc_k(ted(f(n))) for n in N], 8)

# Atari Lynx (Mikey): a 12 bit shift register, the feedback is the parity of the tapped bits (taps 0-5, 7, 10 and 11). Eight sounds: a square, then the tap sets
# whose cycle is closest to 3, 7, 15, 31, 63, 127 and 4095 steps. A short cycle is a tone (the note sets the cycle's rate); a long one is noise
TAPS = (0, 1, 2, 3, 4, 5, 7, 10, 11)
def lynx_cycle(mask):
    def step(st): return ((st << 1) | (bin(st & mask).count("1") & 1)) & 0xFFF
    st = 0xFFF
    for _ in range(4100): st = step(st)           # past any run-in
    s0, n = st, 0
    while True:
        st = step(st); n += 1
        if st == s0: return n
cyc = {}
for m in range(1, 512):
    mask = sum(1 << TAPS[i] for i in range(9) if m >> i & 1)
    c = lynx_cycle(mask)
    if c > 1: cyc.setdefault(c, mask)
LYNX = []
for want in (3, 7, 15, 31, 63, 127, 4095):
    c = min(cyc, key=lambda x: abs(math.log(x / want)))
    LYNX.append((cyc[c], c))
arr("LYNX_MASK", "uint16_t", [0] + [m for m, c in LYNX], 8)
arr("LYNX_LEN", "uint16_t", [2] + [c for m, c in LYNX], 8)
# the long cycles (63, 126, 4095) are played tuned: the register's bit sequence as a running count of ones (so a frame's box average is two lookups)
LYX = []
for m, c in LYNX[4:]:
    st = 0xFFF
    for _ in range(4100): st = ((st << 1) | (bin(st & m).count("1") & 1)) & 0xFFF
    run = [0]
    for _ in range(c):
        st = ((st << 1) | (bin(st & m).count("1") & 1)) & 0xFFF
        run.append(run[-1] + (st & 1))
    LYX += run
arr("LYNX_CUM", "uint16_t", LYX, 16)
# the fastest the chip can step a cycle is its timer's 1 MHz: the largest note phase step per oscillator step (176.4 kHz) for the three tuned cycles
arr("LYNX_CAP", "uint32_t", [round(2 ** 32 * 1e6 / c / FSO) for m, c in LYNX[4:]], 3)

