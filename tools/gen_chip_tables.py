"""Writes firmware/gen/chip_tables.h: pitch, mixer and envelope tables for firmware/src/chips.c.
The chip has no FPU, so everything with a log, a sine or a divide by a real number is computed here.
    python3 tools/gen_chip_tables.py"""
import math
from pathlib import Path

FS, OS = 44100, 4
FSO = FS * OS                                   # the oscillators run at this rate, then average down to FS
NES_CLK, GB_CLK, SMS_CLK = 1789773, 4194304, 3579545
out = []


def f(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def arr(name, ctype, vals, per=12):
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")


def inc_k(hz):                                  # phase step per oscillator step, 32-bit phase: K / period
    return round(2 ** 32 * hz / FSO)


N = range(128)
out.append("/* generated by tools/gen_chip_tables.py: do not edit */")
out.append(f"#define K_NES {inc_k(NES_CLK / 16)}u      /* pulse: inc = K / (t + 1); the triangle is half of it */")
out.append(f"#define K_GB {inc_k(GB_CLK / 32)}u       /* pulse: inc = K / (2048 - x); the wave channel is half of it */")
out.append(f"#define K_SMS {inc_k(SMS_CLK / 32)}u      /* tone: inc = K / n */")

# output stages, one-pole filters at FS: 1 - a = w / (1 + w), w = 2 pi fc / FS. High-pass B in Q16, low-pass A in Q14
def hp_b(fc): w = 2 * math.pi * fc / FS; return round(65536 * w / (1 + w))
def lp_a(fc): w = 2 * math.pi * fc / FS; return round(16384 * w / (1 + w))
for name, fc in (("NES_HP90", 90), ("NES_HP440", 440), ("FAM_HP37", 37), ("GB_HPDMG", -(-math.log(0.999958) * 4194304 / (2 * math.pi))), ("DC_HP14", 14)):
    out.append(f"#define B_{name} {hp_b(abs(fc))}u      /* high-pass {abs(fc):.1f} Hz, Q16 */")
out.append(f"#define A_NES_LP14K {lp_a(14000)}      /* low-pass 14 kHz, Q14 */")

# NES 2A03: pulse f = clk / (16 (t + 1)), triangle f = clk / (32 (t + 1)), 11 bits
arr("NES_PT", "uint16_t", [clamp(round(NES_CLK / (16 * f(n))) - 1, 8, 2047) for n in N])
arr("NES_TT", "uint16_t", [clamp(round(NES_CLK / (32 * f(n))) - 1, 2, 2047) for n in N])
NP = [4, 8, 16, 32, 64, 96, 128, 160, 202, 254, 380, 508, 762, 1016, 2034, 4068]
arr("NES_NSTEP", "uint32_t", [round(NES_CLK / p / FSO * 65536) for p in NP], 8)   # LFSR clocks per step, Q16
arr("NES_PULSE", "int32_t", [round(60000 * (0 if k == 0 else 95.52 / (8128 / k + 100))) for k in range(31)])
arr("NES_TND", "int32_t", [round(60000 * (0 if k == 0 else 163.67 / (24329 / k + 100))) for k in range(203)])

# Game Boy: pulse f = 131072 / (2048 - x), wave f = 65536 / (2048 - x), 11 bits
arr("GB_PX", "uint16_t", [clamp(2048 - round(131072 / f(n)), 0, 2047) for n in N])
arr("GB_WX", "uint16_t", [clamp(2048 - round(65536 / f(n)), 0, 2047) for n in N])
fr = sorted({round(262144 / ((0.5 if r == 0 else r) * 2 ** s), 3) for s in range(14) for r in range(8)}, reverse=True)
out.append(f"#define GB_NNUM {len(fr)}u")
arr("GB_NSTEP", "uint32_t", [round(h / FSO * 65536) for h in fr], 8)              # noise LFSR clocks per step, Q16
waves = [                                       # 4 wave channel presets, 32 x 4 bit
    [15 if i < 16 else 0 for i in range(32)],
    [round(15 * (i % 32) / 31) for i in range(32)],
    [round(15 * (1 - abs(i - 15.5) / 15.5)) for i in range(32)],
    [round(7.5 + 7.5 * math.sin(2 * math.pi * i / 32)) for i in range(32)],
]
out.append("static const uint8_t GB_WAVES[4][32] = {")
for w in waves:
    out.append("    {" + ", ".join(map(str, w)) + "},")
out.append("};")

# SN76489 (Master System): tone f = clk / (32 n), 10 bits; 2 dB per attenuation step
arr("SMS_N", "uint16_t", [clamp(round(SMS_CLK / (32 * f(n))), 1, 1023) for n in N])
arr("SMS_AMP", "int16_t", [0] + [round(4500 * 10 ** (-(15 - v) / 10)) for v in range(1, 16)])
arr("SMS_NSTEP", "uint32_t", [round(SMS_CLK / d / FSO * 65536) for d in (512, 1024, 2048)], 3)

arr("VIB", "int8_t", [round(127 * math.sin(2 * math.pi * i / 32)) for i in range(32)], 16)

dst = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "chip_tables.h"
dst.write_text("\n".join(out) + "\n")
print(dst, len("\n".join(out)), "bytes of source")
