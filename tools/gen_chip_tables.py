def opz_wave(m, i):                             # the OPZ's waves 1..7 at phase i / 1024: squared, half, half squared, alternating, ..., camel squared (0 is the sine)
    s = SINT[i]
    if m & 2 and s < 0:
        s = 0
    if m >= 4:
        if i >> 9:
            return 0
        s = SINT[(2 * i) & 1023]
        if m >= 6 and s < 0:
            s = -s
    if m & 1:
        s = s * abs(s) >> 14
    return s


